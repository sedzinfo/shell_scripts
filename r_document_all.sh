#!/usr/bin/env bash
# Updates the help pages (man/*.Rd) and NAMESPACE of every R package in
# ~/GitHub (or the folder given) from their roxygen comments, one after the
# other, with roxygen2::roxygenise() (what devtools::document() does for one
# package). r_cmd_check.sh, r_pkgdown_all.sh and r_pdf_all.sh use man/ as it is,
# so run this first. It reports which packages failed and which files changed,
# to commit and push. Nothing is committed or pushed.
#   r_document_all.sh [folder] [package ...]   every package, or only the ones named
#   r_document_all.sh --check                  only lists the packages whose help pages
#                                              or NAMESPACE are out of date: roxygen
#                                              runs on a copy, nothing is changed
# A package is a folder with a DESCRIPTION: a repository, or a folder in one
# (rwf/rwf). Mirror repositories with the same package (crypto and golemcrypto)
# are each documented. Packages without roxygen comments are skipped. The exit
# code is 1 if any failed, or with --check if any is out of date.

root="$HOME/GitHub"; check=0; only=(); root_given=0
for arg in "$@"; do
  case "$arg" in
    --check)   check=1 ;;
    -h|--help) sed -n '2,/^$/{s/^# \{0,1\}//;p}' "$0"; exit 0 ;;
    -*)        echo "Unknown option: $arg (see --help)"; exit 1 ;;
    *)
      if [ $root_given -eq 0 ] && [ -d "${arg/#\~/$HOME}" ]; then
        root="${arg/#\~/$HOME}"; root_given=1
      else
        only+=("$arg")
      fi ;;
  esac
done

# ask for the folder until one that exists is given (Tab completes paths, ~ works)
while [ ! -d "$root" ]; do
  echo "Folder not found: $root"
  read -e -r -p "Folder with the repositories (empty to quit): " root || exit 1
  [ -z "$root" ] && exit 1
  root="${root/#\~/$HOME}"
done
root=$(cd "$root" && pwd)

red=$'\e[31m'; yellow=$'\e[33m'; green=$'\e[32m'; bold=$'\e[1m'; reset=$'\e[0m'

# a line of 80 # characters, between the packages
separator() { printf '#%.0s' {1..80}; printf '\n'; }

yes_no() {
  local answer
  read -r -p "$1 [y/N]: " answer
  [[ "$answer" =~ ^[Yy]([Ee][Ss])?$ ]]
}

# offers to install the programs this script needs, when they are missing.
# Each argument is program:package:what it is for. It only asks (never installs
# by itself), only once, and only where apt exists; with no, the script goes on
# and shows what it can.
check_packages() {
  local entry program package purpose answer packages=() lines=()
  for entry in "$@"; do
    IFS=: read -r program package purpose <<< "$entry"
    if ! command -v "$program" > /dev/null; then
      packages+=("$package")
      lines+=("$(printf '%-14s %-26s package %s' "$program" "($purpose)" "$package")")
    fi
  done
  [ ${#packages[@]} -eq 0 ] && return 0
  echo "Missing:"
  printf '  %s\n' "${lines[@]}"
  if command -v apt-get > /dev/null && [ -t 0 ]; then
    read -r -p "Install them now with sudo apt install ${packages[*]}? [y/N]: " answer
    if [[ "$answer" =~ ^[Yy]([Ee][Ss])?$ ]]; then
      sudo apt install -y "${packages[@]}"
    fi
  else
    echo "Install them with the package manager of this system: ${packages[*]}"
  fi
}

# R and roxygen2 are needed, so without them it stops
check_packages 'Rscript:r-base-dev:runs R'
command -v Rscript > /dev/null || exit 1
if ! Rscript -e 'quit(status = as.integer(!requireNamespace("roxygen2", quietly = TRUE)))' 2> /dev/null; then
  echo "The R package roxygen2 is not installed."
  yes_no "Install it now, into your R library?" || exit 1
  Rscript -e 'lib <- Sys.getenv("R_LIBS_USER"); dir.create(lib, recursive = TRUE, showWarnings = FALSE)
              install.packages("roxygen2", lib = lib, repos = "https://cloud.r-project.org")' || exit 1
fi
installed=$(Rscript -e 'cat(as.character(packageVersion("roxygen2")))' 2> /dev/null)

# whether a package is documented with roxygen: its DESCRIPTION names the
# roxygen2 version, or its NAMESPACE or a help page says roxygen2 wrote it
uses_roxygen() {
  grep -qE '^(RoxygenNote|Config/roxygen2/version):' "$1/DESCRIPTION" ||
    grep -qs 'Generated by roxygen2' "$1/NAMESPACE" "$1"/man/*.Rd
}

# the packages: every folder with a DESCRIPTION, by folder, as each repository
# has its own help pages
dirs=(); no_roxygen=()
while IFS= read -r description; do
  dir=$(dirname "$description")
  name=$(awk -F': *' '$1 == "Package" { print $2; exit }' "$description")
  [ -n "$name" ] || continue
  if [ ${#only[@]} -gt 0 ]; then
    wanted=0
    for want in "${only[@]}"; do
      [ "$want" = "$name" ] || [ "$want" = "$(basename "$dir")" ] && wanted=1
    done
    [ $wanted -eq 1 ] || continue
  fi
  if uses_roxygen "$dir"; then
    dirs+=("$dir")
  else
    no_roxygen+=("${dir#"$root"/}")
  fi
done < <(find "$root" -maxdepth 3 \
           \( -name .git -o -name '*.Rcheck' -o -name renv -o -name venv -o -name .venv -o -name node_modules \) -prune \
           -o -name DESCRIPTION -type f -print | sort)
if [ ${#dirs[@]} -eq 0 ]; then
  echo "No R packages with roxygen comments${only[*]:+ named ${only[*]}} in $root"
  exit 1
fi

out="${XDG_CACHE_HOME:-$HOME/.cache}/r_document_all"
mkdir -p "$out"

# the copy that --check works on, removed after each package and at the end, also
# after Ctrl+C; only ever a folder this script made in $out
copy=""
remove_copy() {
  case "$copy" in
    "$out"/copy.?*) rm -rf -- "$copy" ;;
  esac
  copy=""
}
trap remove_copy EXIT
trap 'exit 130' INT TERM

# minutes and seconds
duration() { printf '%dm%02ds' $(($1 / 60)) $(($1 % 60)); }

# a checksum per file roxygen writes: the help pages, NAMESPACE and DESCRIPTION.
# With --check the roxygen2 version in DESCRIPTION is left out: roxygen updates it
# whenever another version runs, which does not make the help pages out of date
snapshot() {
  (cd "$1" || exit
   find man -maxdepth 1 -type f -name '*.Rd' -print0 2> /dev/null | sort -z | xargs -0 -r md5sum
   [ -f NAMESPACE ] && md5sum NAMESPACE
   if [ $check -eq 1 ]; then
     printf '%s  DESCRIPTION\n' "$(grep -vE '^(RoxygenNote|Config/roxygen2/version):' DESCRIPTION | md5sum | cut -d' ' -f1)"
   else
     md5sum DESCRIPTION
   fi)
}

# the files whose checksum differs between two snapshots: changed, new or removed
changed_files() {
  diff <(printf '%s\n' "$1") <(printf '%s\n' "$2") | sed -n 's/^[<>] [0-9a-f]\{32\}  //p' | sort -u
}

# a copy of a package for --check: what roxygen writes (man/, NAMESPACE,
# DESCRIPTION) and what loading the package may write (R/ and src/, e.g.
# RcppExports, vignettes/) is copied; everything else is linked, so that big
# data is not copied and nothing can change in the package itself
copy_of() {
  local entry dest
  dest=$(mktemp -d "$out/copy.XXXXXX") || return 1
  for entry in "$1"/* "$1"/.[!.]*; do
    [ -e "$entry" ] || continue
    case "$(basename "$entry")" in
      .git) ;;
      DESCRIPTION|NAMESPACE|R|man|src|vignettes) cp -a "$entry" "$dest/" ;;
      *) ln -s "$entry" "$dest/" ;;
    esac
  done
  echo "$dest"
}

if [ $check -eq 1 ]; then
  echo "Checking ${#dirs[@]} package(s) in $root against their roxygen comments (roxygen2 $installed); logs in $out"
else
  echo "Documenting ${#dirs[@]} package(s) in $root (roxygen2 $installed); logs in $out"
fi
[ ${#no_roxygen[@]} -gt 0 ] && echo "Skipped, no roxygen comments: ${no_roxygen[*]}"

failed=(); out_of_date=(); to_commit=(); summary=()
for dir in "${dirs[@]}"; do
  label=${dir#"$root"/}
  name=$(awk -F': *' '$1 == "Package" { print $2; exit }' "$dir/DESCRIPTION")
  recorded=$(awk -F': *' '$1 == "Config/roxygen2/version" || $1 == "RoxygenNote" { print $2; exit }' "$dir/DESCRIPTION")
  log="$out/${label//\//_}.log"
  echo
  separator
  echo "${bold}$name${reset}  ($label)"
  start=$SECONDS

  before=$(snapshot "$dir")
  description_before=$(grep -vE '^(RoxygenNote|Config/roxygen2/version):' "$dir/DESCRIPTION" | md5sum)
  target=$dir
  if [ $check -eq 1 ]; then
    copy=$(copy_of "$dir"); target=$copy
  fi
  # roxygen loads the package (pkgload::load_all) to read its objects, so the
  # packages it uses must be installed (r_install_packages.sh installs them)
  if Rscript -e 'roxygen2::roxygenise(commandArgs(TRUE)[1])' "$target" > "$log" 2>&1; then
    changed=$(changed_files "$before" "$(snapshot "$target")")
    # roxygen writes the version that ran into DESCRIPTION; say so when that is all
    [ "$description_before" = "$(grep -vE '^(RoxygenNote|Config/roxygen2/version):' "$target/DESCRIPTION" | md5sum)" ] &&
      changed=$(sed 's/^DESCRIPTION$/DESCRIPTION (roxygen2 version)/' <<< "$changed")
    count=$(grep -c . <<< "$changed")
    files=$(head -n 10 <<< "$changed" | tr '\n' ' ')
    [ "$count" -gt 10 ] && files="$files... ($count in all)"
    if [ "$count" -eq 0 ]; then
      result="up to date"
      echo "  ${green}$result${reset}"
    elif [ $check -eq 1 ]; then
      result="out of date: $count files"
      out_of_date+=("$label")
      echo "  ${yellow}$result${reset}: $files"
      # another major or minor roxygen2 version also lays files out differently
      [ -n "$recorded" ] && [ "${recorded%.*}" != "${installed%.*}" ] &&
        echo "    written with roxygen2 $recorded, this is $installed: some differences may only be layout"
    else
      result="updated $count files"
      to_commit+=("$(git -C "$dir" rev-parse --show-toplevel 2> /dev/null | xargs -r basename)")
      echo "  ${green}$result${reset}: $files"
    fi
    # roxygen's warnings (lines starting with ✖ or !), such as a @param without
    # a description or a link to a topic that does not exist
    grep -E '^(✖|!) |^Warning' "$log" | sort -u | head -n 10 | sed "s/^/    ${yellow}/; s/\$/${reset}/"
  else
    result="failed"
    failed+=("$name ($label)")
    echo "  ${red}failed${reset}; the end of $log:"
    tail -n 15 "$log" | sed 's/^/    /'
  fi
  remove_copy
  summary+=("$(printf '%-32s %-10s %s' "$label" "$(duration $((SECONDS - start)))" "$result")")
done

echo
separator
echo "${bold}Summary${reset}"
printf '  %s\n' "${summary[@]}"
echo
if [ ${#failed[@]} -gt 0 ]; then
  echo "${red}Failed in ${#failed[@]}:${reset}"
  printf '  %s\n' "${failed[@]}"
fi
if [ ${#out_of_date[@]} -gt 0 ]; then
  echo "${yellow}Out of date in ${#out_of_date[@]}:${reset} ${out_of_date[*]}"
  echo "  r_document_all.sh ${out_of_date[*]##*/} updates them; git diff then shows what changed"
fi
to_commit=($(printf '%s\n' "${to_commit[@]}" | grep . | sort -u))
if [ ${#to_commit[@]} -gt 0 ]; then
  echo "Changed, to commit and push: ${to_commit[*]}"
fi
[ ${#failed[@]} -eq 0 ] && [ ${#out_of_date[@]} -eq 0 ]
